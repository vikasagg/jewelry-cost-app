-- One database per shop (tenant). Runs unchanged on H2 (local mode, PostgreSQL
-- compatibility) and PostgreSQL (cloud mode). Money, weights and rates are
-- NUMERIC with 3 decimals (owner decision D-04).

-- ---------- configuration, users, audit ----------
CREATE TABLE app_config (
    config_key   VARCHAR(100) PRIMARY KEY,
    config_value VARCHAR(500),
    description  VARCHAR(300),
    updated_by   VARCHAR(60),
    updated_at   TIMESTAMP
);

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(60)  NOT NULL UNIQUE,
    full_name     VARCHAR(120) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    username    VARCHAR(60),
    action      VARCHAR(60)  NOT NULL,
    entity      VARCHAR(40),
    entity_id   VARCHAR(60),
    detail      VARCHAR(1000)
);

CREATE TABLE doc_sequence (
    series      VARCHAR(40) PRIMARY KEY,
    next_value  BIGINT NOT NULL
);

-- ---------- masters ----------
CREATE TABLE location (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code  VARCHAR(30)  NOT NULL UNIQUE,
    name  VARCHAR(100) NOT NULL,
    kind  VARCHAR(20)  NOT NULL          -- COUNTER | VAULT | REPAIR | EXTERNAL
);

CREATE TABLE category (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(30)  NOT NULL UNIQUE,
    name            VARCHAR(100) NOT NULL,
    family          VARCHAR(20)  NOT NULL,   -- GOLD | DIAMOND | PLATINUM | SILVER | SILVER_ORNAMENT | GIFTING
    metal           VARCHAR(20),             -- GOLD | SILVER | PLATINUM | null for gifting
    pricing_mode    VARCHAR(20)  NOT NULL,   -- METAL | FIXED
    tracking        VARCHAR(20)  NOT NULL,   -- PIECE | QUANTITY
    tag_type        VARCHAR(10)  NOT NULL,   -- QR | RFID
    making_type     VARCHAR(20)  NOT NULL DEFAULT 'PER_GRAM',  -- PER_GRAM | PERCENT | FIXED
    making_value    NUMERIC(18,3) NOT NULL DEFAULT 0,
    wastage_pct     NUMERIC(9,3)  NOT NULL DEFAULT 0,
    gst_pct         NUMERIC(9,3)  NOT NULL DEFAULT 3,
    active          BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE purity (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metal      VARCHAR(20)  NOT NULL,
    code       VARCHAR(10)  NOT NULL,
    price_factor NUMERIC(10,6) NOT NULL,   -- share of the base (24K / fine) rate used for selling price
    fineness   NUMERIC(10,6) NOT NULL,     -- true metal content, used for fine weight
    sort_order INT NOT NULL DEFAULT 0,
    active     BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (metal, code)
);

CREATE TABLE party (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_type  VARCHAR(20)  NOT NULL,     -- CUSTOMER | VENDOR | KARIGAR
    name        VARCHAR(150) NOT NULL,
    phone       VARCHAR(20),
    email       VARCHAR(120),
    address     VARCHAR(300),
    gstin       VARCHAR(20),
    pan         VARCHAR(15),
    id_proof    VARCHAR(40),
    birthday    DATE,
    anniversary DATE,
    notes       VARCHAR(500),
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_party_type ON party (party_type);
CREATE INDEX ix_party_phone ON party (phone);

-- ---------- metal rates ----------
CREATE TABLE rate_set (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date  DATE NOT NULL,
    source         VARCHAR(20) NOT NULL,          -- MANUAL | LIVE
    provider       VARCHAR(60),
    gold_24k       NUMERIC(18,3) NOT NULL,        -- per gram
    silver_base    NUMERIC(18,3) NOT NULL,        -- per gram, fine silver
    platinum_base  NUMERIC(18,3) NOT NULL,        -- per gram
    status         VARCHAR(20) NOT NULL,          -- PROPOSED | APPROVED | REJECTED | SUPERSEDED
    entered_by     VARCHAR(60),
    entered_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_by    VARCHAR(60),
    approved_at    TIMESTAMP,
    note           VARCHAR(300)
);
CREATE INDEX ix_rate_set_date ON rate_set (business_date, status);

CREATE TABLE rate_line (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_set_id   BIGINT NOT NULL REFERENCES rate_set(id),
    metal         VARCHAR(20) NOT NULL,
    purity_code   VARCHAR(10) NOT NULL,
    rate_per_gram NUMERIC(18,3) NOT NULL
);

-- ---------- items and stock ----------
CREATE TABLE item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag_code      VARCHAR(40)  NOT NULL UNIQUE,   -- printed on the QR label
    rfid_epc      VARCHAR(64)  UNIQUE,            -- reserved for RFID phase
    category_id   BIGINT NOT NULL REFERENCES category(id),
    name          VARCHAR(150) NOT NULL,
    metal         VARCHAR(20),
    purity_code   VARCHAR(10),
    gross_wt      NUMERIC(18,3) NOT NULL DEFAULT 0,
    stone_wt      NUMERIC(18,3) NOT NULL DEFAULT 0,
    net_wt        NUMERIC(18,3) NOT NULL DEFAULT 0,
    making_type   VARCHAR(20),
    making_value  NUMERIC(18,3),
    wastage_pct   NUMERIC(9,3),
    fixed_price   NUMERIC(18,3),
    quantity      INT NOT NULL DEFAULT 1,
    huid          VARCHAR(20),
    design_code   VARCHAR(40),
    collection    VARCHAR(60),
    location_id   BIGINT REFERENCES location(id),
    status        VARCHAR(20)  NOT NULL,          -- IN_STOCK | RESERVED | SOLD | WITH_KARIGAR | RETURNED | LOST
    vendor_id     BIGINT REFERENCES party(id),
    purchase_id   BIGINT,
    purchase_class VARCHAR(10),                   -- SEEN | UNSEEN
    cost_amount   NUMERIC(18,3),
    notes         VARCHAR(500),
    created_by    VARCHAR(60),
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_item_status ON item (status);
CREATE INDEX ix_item_category ON item (category_id);

CREATE TABLE stone (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id       BIGINT NOT NULL REFERENCES item(id),
    stone_type    VARCHAR(30) NOT NULL,           -- DIAMOND | RUBY | EMERALD | CZ | OTHER
    pieces        INT NOT NULL DEFAULT 1,
    carat         NUMERIC(18,3) NOT NULL DEFAULT 0,
    rate_per_carat NUMERIC(18,3) NOT NULL DEFAULT 0,
    stone_value   NUMERIC(18,3) NOT NULL DEFAULT 0,
    clarity       VARCHAR(20),
    colour        VARCHAR(20),
    certificate   VARCHAR(60)
);
CREATE INDEX ix_stone_item ON stone (item_id);

-- Every stock change is one row here. Item status is a cache maintained only by
-- the posting service; the ledger is the source of truth (BRD FR-STK-01..03).
CREATE TABLE stock_movement (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id        BIGINT NOT NULL REFERENCES item(id),
    movement_type  VARCHAR(30) NOT NULL,
    qty            INT NOT NULL,                  -- +1 in, -1 out
    gross_wt       NUMERIC(18,3) NOT NULL,
    net_wt         NUMERIC(18,3) NOT NULL,
    status_after   VARCHAR(20) NOT NULL,
    doc_type       VARCHAR(20),
    doc_id         BIGINT,
    business_date  DATE NOT NULL,
    username       VARCHAR(60),
    created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    idem_key       VARCHAR(100) NOT NULL UNIQUE,
    note           VARCHAR(300)
);
CREATE INDEX ix_movement_item ON stock_movement (item_id);
CREATE INDEX ix_movement_date ON stock_movement (business_date);

-- ---------- purchase ----------
CREATE TABLE purchase (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_no      VARCHAR(40) NOT NULL UNIQUE,
    business_date    DATE NOT NULL,
    party_id         BIGINT REFERENCES party(id),
    purchase_kind    VARCHAR(20) NOT NULL,        -- FINISHED | OLD_METAL | GIFTING
    payment_mode     VARCHAR(20) NOT NULL,        -- CASH | BANK | GOLD | SILVER | MIXED | CREDIT
    gst_invoice_no   VARCHAR(60),
    taxable_amount   NUMERIC(18,3) NOT NULL DEFAULT 0,
    gst_amount       NUMERIC(18,3) NOT NULL DEFAULT 0,
    total_amount     NUMERIC(18,3) NOT NULL DEFAULT 0,
    cash_paid        NUMERIC(18,3) NOT NULL DEFAULT 0,
    bank_paid        NUMERIC(18,3) NOT NULL DEFAULT 0,
    bank_ref         VARCHAR(60),
    gold_fine_paid   NUMERIC(18,3) NOT NULL DEFAULT 0,
    silver_fine_paid NUMERIC(18,3) NOT NULL DEFAULT 0,
    metal_value_paid NUMERIC(18,3) NOT NULL DEFAULT 0,
    balance_due      NUMERIC(18,3) NOT NULL DEFAULT 0,
    purchase_class   VARCHAR(10) NOT NULL,        -- SEEN | UNSEEN
    rate_set_id      BIGINT REFERENCES rate_set(id),
    notes            VARCHAR(500),
    created_by       VARCHAR(60),
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE purchase_line (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id   BIGINT NOT NULL REFERENCES purchase(id),
    item_id       BIGINT REFERENCES item(id),
    description   VARCHAR(200) NOT NULL,
    metal         VARCHAR(20),
    purity_code   VARCHAR(10),
    gross_wt      NUMERIC(18,3) NOT NULL DEFAULT 0,
    net_wt        NUMERIC(18,3) NOT NULL DEFAULT 0,
    fine_wt       NUMERIC(18,3) NOT NULL DEFAULT 0,
    rate          NUMERIC(18,3) NOT NULL DEFAULT 0,
    deduction_pct NUMERIC(9,3)  NOT NULL DEFAULT 0,
    quantity      INT NOT NULL DEFAULT 1,
    amount        NUMERIC(18,3) NOT NULL DEFAULT 0
);

-- ---------- sales ----------
CREATE TABLE sale (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no      VARCHAR(40) NOT NULL UNIQUE,
    business_date   DATE NOT NULL,
    customer_id     BIGINT REFERENCES party(id),
    rate_set_id     BIGINT NOT NULL REFERENCES rate_set(id),
    items_total     NUMERIC(18,3) NOT NULL,       -- sum of line totals incl. GST
    discount        NUMERIC(18,3) NOT NULL DEFAULT 0,
    taxable_total   NUMERIC(18,3) NOT NULL,
    gst_total       NUMERIC(18,3) NOT NULL,
    exchange_total  NUMERIC(18,3) NOT NULL DEFAULT 0,
    round_off       NUMERIC(18,3) NOT NULL DEFAULT 0,
    net_payable     NUMERIC(18,3) NOT NULL,
    paid_total      NUMERIC(18,3) NOT NULL DEFAULT 0,
    balance_due     NUMERIC(18,3) NOT NULL DEFAULT 0,
    status          VARCHAR(20) NOT NULL,         -- FINAL | RETURNED
    notes           VARCHAR(500),
    created_by      VARCHAR(60),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_sale_date ON sale (business_date);

CREATE TABLE sale_line (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id       BIGINT NOT NULL REFERENCES sale(id),
    item_id       BIGINT NOT NULL REFERENCES item(id),
    description   VARCHAR(200) NOT NULL,
    metal         VARCHAR(20),
    purity_code   VARCHAR(10),
    quantity      INT NOT NULL DEFAULT 1,
    net_wt        NUMERIC(18,3) NOT NULL DEFAULT 0,
    rate          NUMERIC(18,3) NOT NULL DEFAULT 0,
    metal_value   NUMERIC(18,3) NOT NULL DEFAULT 0,
    wastage_value NUMERIC(18,3) NOT NULL DEFAULT 0,
    making_value  NUMERIC(18,3) NOT NULL DEFAULT 0,
    stone_value   NUMERIC(18,3) NOT NULL DEFAULT 0,
    discount      NUMERIC(18,3) NOT NULL DEFAULT 0,
    taxable       NUMERIC(18,3) NOT NULL DEFAULT 0,
    gst_pct       NUMERIC(9,3)  NOT NULL DEFAULT 0,
    gst           NUMERIC(18,3) NOT NULL DEFAULT 0,
    line_total    NUMERIC(18,3) NOT NULL DEFAULT 0,
    huid          VARCHAR(20)
);

CREATE TABLE sale_exchange (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id       BIGINT NOT NULL REFERENCES sale(id),
    description   VARCHAR(200) NOT NULL,
    metal         VARCHAR(20) NOT NULL,
    purity_code   VARCHAR(10) NOT NULL,
    gross_wt      NUMERIC(18,3) NOT NULL,
    net_wt        NUMERIC(18,3) NOT NULL,
    fine_wt       NUMERIC(18,3) NOT NULL,
    rate          NUMERIC(18,3) NOT NULL,
    deduction_pct NUMERIC(9,3)  NOT NULL DEFAULT 0,
    exchange_value NUMERIC(18,3) NOT NULL
);

-- Money and metal received or paid against any document.
CREATE TABLE payment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_type    VARCHAR(20) NOT NULL,             -- SALE | PURCHASE | REPAIR | RECEIPT | VOUCHER | RETURN
    doc_id      BIGINT NOT NULL,
    party_id    BIGINT REFERENCES party(id),
    direction   VARCHAR(5)  NOT NULL,             -- IN | OUT
    mode        VARCHAR(20) NOT NULL,             -- CASH | UPI | CARD | BANK | CHEQUE
    amount      NUMERIC(18,3) NOT NULL,
    reference   VARCHAR(60),
    business_date DATE NOT NULL,
    created_by  VARCHAR(60),
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Books: CASH, BANK in rupees; GOLD, SILVER, PLATINUM in fine grams.
CREATE TABLE ledger_entry (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book          VARCHAR(20) NOT NULL,
    business_date DATE NOT NULL,
    party_id      BIGINT REFERENCES party(id),
    doc_type      VARCHAR(20) NOT NULL,
    doc_id        BIGINT NOT NULL,
    debit         NUMERIC(18,3) NOT NULL DEFAULT 0,   -- in
    credit        NUMERIC(18,3) NOT NULL DEFAULT 0,   -- out
    narration     VARCHAR(300),
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_ledger_book ON ledger_entry (book, business_date);

-- ---------- repair ----------
CREATE TABLE repair_job (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_no          VARCHAR(40) NOT NULL UNIQUE,
    customer_id     BIGINT NOT NULL REFERENCES party(id),
    description     VARCHAR(200) NOT NULL,
    metal           VARCHAR(20),
    purity_code     VARCHAR(10),
    weight_in       NUMERIC(18,3) NOT NULL,
    item_condition  VARCHAR(300),
    repair_type     VARCHAR(100),
    estimate        NUMERIC(18,3) NOT NULL DEFAULT 0,
    promised_date   DATE,
    status          VARCHAR(20) NOT NULL,         -- RECEIVED | WITH_KARIGAR | IN_PROGRESS | READY | DELIVERED
    karigar_id      BIGINT REFERENCES party(id),
    weight_issued   NUMERIC(18,3),
    weight_returned NUMERIC(18,3),
    extra_metal_wt  NUMERIC(18,3) NOT NULL DEFAULT 0,
    weight_out      NUMERIC(18,3),
    charges         NUMERIC(18,3),
    paid            NUMERIC(18,3) NOT NULL DEFAULT 0,
    created_by      VARCHAR(60),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delivered_at    TIMESTAMP
);

CREATE TABLE repair_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id      BIGINT NOT NULL REFERENCES repair_job(id),
    status      VARCHAR(20) NOT NULL,
    weight      NUMERIC(18,3),
    note        VARCHAR(300),
    username    VARCHAR(60),
    at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------- daily tally ----------
CREATE TABLE tally_session (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_date DATE NOT NULL,
    location_id   BIGINT REFERENCES location(id),
    category_id   BIGINT REFERENCES category(id),
    status        VARCHAR(20) NOT NULL,           -- OPEN | CLOSED
    expected_count INT NOT NULL DEFAULT 0,
    opened_by     VARCHAR(60),
    opened_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_by     VARCHAR(60),
    closed_at     TIMESTAMP,
    notes         VARCHAR(500)
);

CREATE TABLE tally_expected (
    session_id  BIGINT NOT NULL REFERENCES tally_session(id),
    item_id     BIGINT NOT NULL REFERENCES item(id),
    PRIMARY KEY (session_id, item_id)
);

CREATE TABLE tally_scan (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  BIGINT NOT NULL REFERENCES tally_session(id),
    code        VARCHAR(64) NOT NULL,
    item_id     BIGINT REFERENCES item(id),
    username    VARCHAR(60),
    scanned_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (session_id, code)
);

CREATE TABLE tally_variance (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  BIGINT NOT NULL REFERENCES tally_session(id),
    kind        VARCHAR(20) NOT NULL,             -- MISSING | UNEXPECTED | UNKNOWN
    item_id     BIGINT REFERENCES item(id),
    code        VARCHAR(64),
    resolution  VARCHAR(20),                      -- null = open | FOUND | MARK_LOST | ACCEPTED
    reason      VARCHAR(300),
    resolved_by VARCHAR(60),
    resolved_at TIMESTAMP
);

-- ---------- backups ----------
CREATE TABLE backup_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    username    VARCHAR(60),
    file_name   VARCHAR(200) NOT NULL,
    target      VARCHAR(300),
    size_bytes  BIGINT NOT NULL,
    sha256      VARCHAR(64) NOT NULL,
    row_count   BIGINT NOT NULL,
    verified    BOOLEAN NOT NULL
);
